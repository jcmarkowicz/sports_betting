def select_prediction_export_columns(frame, output_path=None):
    name = Path(output_path).name if output_path is not None else ''
    columns = _BASE_COLUMNS + _SUFFIXES.get(name, _SUFFIXES['test_logit_open_with_open.csv'])
    missing = set(columns) - set(frame.columns)
    if missing:
        raise ValueError(f'Missing prediction export columns: {sorted(missing)}')
    return frame.loc[:, columns].copy()
